def _normal(name):
    text = (name or '').strip()
    for mark in ('㈜', '(주)', '주식회사'):
        text = text.replace(mark, '')
    return ''.join(text.split())


def private_group(name):
    """이름 → 재계순위 그룹 이름(공정위 표기). 순위 밖이면 None."""
    normal = _normal(name)
    if normal in KNOWN:
        return KNOWN[normal]
    upper = normal.upper()
    for prefix, group in PREFIXES:
        if upper.startswith(prefix):
            return group
    for word, group in CONTAINS:
        if word in normal:
            return group
    return None


def private_sort_key(name):
    """민간 정렬 키: (재계순위, 대표 계열사 0 / 나머지 1, 이름). 순위 밖은 맨 뒤 가나다."""
    normal = _normal(name)
    group = private_group(name)
    rank = _RANK.get(group, len(RANKING) + 1) if group else len(RANKING) + 1
    flagship = 0 if group and _normal(FLAGSHIP.get(group, '')) == normal else 1
    return (rank, flagship, (name or '').strip().casefold())
